//! Extensible Alerting Subsystem for Pulsar EDR.
//!
//! Provides a strongly-typed, Serde-serializable security alert model decoupled
//! across Actor, Target, Operation, MITRE ATT&CK taxonomy, and Mitigation outcomes.

use std::collections::HashMap;
use std::fmt;
use serde::{Deserialize, Serialize};
use uuid::Uuid;

pub mod context;
pub mod emitter;

pub use context::{ActorContext, OperationContext, OperationType, TargetContext};
pub use emitter::{AlertEmitter, ConsoleEmitter};

/// Alert triage severity rating.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum AlertSeverity {
    /// Informational event or harmless baseline deviation.
    Informational = 0,
    /// Low-confidence anomalous activity.
    Low = 1,
    /// Suspicious behavior requiring investigation.
    Medium = 2,
    /// High-confidence malicious activity or common offensive tooling.
    High = 3,
    /// Confirmed critical exploit, credential dump, or system tampering.
    Critical = 4,
}

impl fmt::Display for AlertSeverity {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Informational => write!(f, "INFORMATIONAL"),
            Self::Low => write!(f, "LOW"),
            Self::Medium => write!(f, "MEDIUM"),
            Self::High => write!(f, "HIGH"),
            Self::Critical => write!(f, "CRITICAL"),
        }
    }
}

/// MITRE ATT&CK taxonomy categorization.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct MitreAttack {
    /// ATT&CK Tactic name (e.g. "Credential Access").
    pub tactic: String,
    /// ATT&CK Technique ID (e.g. "T1003").
    pub technique_id: String,
    /// ATT&CK Sub-technique ID (e.g. Some("T1003.001")).
    pub subtechnique_id: Option<String>,
    /// ATT&CK Technique name (e.g. "OS Credential Dumping: LSASS Memory").
    pub technique_name: String,
}

impl Default for MitreAttack {
    fn default() -> Self {
        Self {
            tactic: "Credential Access".to_string(),
            technique_id: "T1003".to_string(),
            subtechnique_id: Some("T1003.001".to_string()),
            technique_name: "OS Credential Dumping: LSASS Memory".to_string(),
        }
    }
}

/// Mitigation or response action outcome applied to the operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum MitigationStatus {
    /// The threat was neutralized or degraded by kernel/user-mode protection.
    Mitigated,
    /// The offensive process was terminated by user-mode response policy.
    Terminated,
    /// Observed and audited without intervention.
    AuditedOnly,
}

impl fmt::Display for MitigationStatus {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Mitigated => write!(f, "MITIGATED"),
            Self::Terminated => write!(f, "TERMINATED"),
            Self::AuditedOnly => write!(f, "AUDITED_ONLY"),
        }
    }
}

/// Primary security incident record generated by analytical sinks and rule engines.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Alert {
    /// Unique identifier for this alert instance.
    pub id: Uuid,
    /// UTC timestamp in epoch milliseconds.
    pub timestamp: i64,
    /// Alert triage severity.
    pub severity: AlertSeverity,
    /// Concise summary title.
    pub title: String,
    /// Detailed incident explanation and rationale.
    pub description: String,
    /// Associated MITRE ATT&CK taxonomy metadata.
    pub mitre: MitreAttack,
    /// Offending actor process details.
    pub actor: ActorContext,
    /// Targeted entity details.
    pub target: TargetContext,
    /// Technical operation parameters.
    pub operation: OperationContext,
    /// Mitigation response status.
    pub mitigation: MitigationStatus,
    /// Name or path of the rule that generated the alert.
    pub rule_name: Option<String>,
    /// Arbitrary rule-defined metadata tags.
    pub tags: HashMap<String, String>,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_alert_json_serialization_roundtrip() {
        let alert = Alert {
            id: Uuid::new_v4(),
            timestamp: 1775731200000,
            severity: AlertSeverity::Critical,
            title: "LSASS Memory Access via Comsvcs DLL".to_string(),
            description: "Process attempted minidump export".to_string(),
            mitre: MitreAttack {
                tactic: "Credential Access".to_string(),
                technique_id: "T1003".to_string(),
                subtechnique_id: Some("T1003.001".to_string()),
                technique_name: "OS Credential Dumping: LSASS Memory".to_string(),
            },
            actor: ActorContext {
                pid: 5120,
                name: "rundll32.exe".to_string(),
                image_path: "C:\\Windows\\System32\\rundll32.exe".to_string(),
                command_line: "rundll32.exe comsvcs.dll, MiniDump 816 C:\\temp\\lsass.dmp full".to_string(),
                user_sid: "S-1-5-18".to_string(),
                session_id: 1,
                integrity_level: 0x4000,
                signature_level: 14,
                protection: 0,
                parent_pid: 4920,
                parent_name: "cmd.exe".to_string(),
                ancestry: vec!["explorer.exe".to_string(), "cmd.exe".to_string(), "rundll32.exe".to_string()],
            },
            target: TargetContext {
                pid: 816,
                name: "lsass.exe".to_string(),
                entity_type: "Process".to_string(),
            },
            operation: OperationContext {
                operation_type: OperationType::ProcessHandleCreate,
                desired_access: 0x001FFFFF,
                granted_access: 0x00001000,
                requested_rights: vec!["PROCESS_ALL_ACCESS".to_string(), "PROCESS_VM_READ".to_string()],
                details: HashMap::new(),
            },
            mitigation: MitigationStatus::Mitigated,
            rule_name: Some("rules/detectors/credential_access/lsass_comsvcs.rhai".to_string()),
            tags: HashMap::from([("sensor".to_string(), "singularity_callbacks".to_string())]),
        };

        let json = serde_json::to_string_pretty(&alert).expect("serialization should succeed");
        assert!(json.contains("\"severity\": \"critical\""));
        assert!(json.contains("\"techniqueId\": \"T1003\""));
        assert!(json.contains("\"operationType\": \"processHandleCreate\""));
        assert!(json.contains("\"mitigation\": \"mitigated\""));

        let deserialized: Alert = serde_json::from_str(&json).expect("deserialization should succeed");
        assert_eq!(alert, deserialized);
    }
}
